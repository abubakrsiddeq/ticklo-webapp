#!/usr/bin/env node
/**
 * Generate `lib/database.types.ts` (Supabase "Database" type format) from a
 * local Postgres that has the TickLO migrations applied.
 *
 * `supabase gen types` needs Docker; this script only needs a local Postgres:
 *   ../scripts/db-reset-local.sh && npm run db:types
 *
 * When you have a hosted project you can use the official generator instead:
 *   supabase gen types typescript --project-id <ref> --schema public > lib/database.types.ts
 */
import pg from "pg";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, "../lib/database.types.ts");
const url = process.env.TYPEGEN_DATABASE_URL ?? "postgres:///ticklo_test";

const client = new pg.Client({ connectionString: url });
await client.connect();

const q = async (sql, params = []) => (await client.query(sql, params)).rows;

const enums = await q(`
  select t.typname as name, array_agg(e.enumlabel::text order by e.enumsortorder) as labels
  from pg_type t
  join pg_enum e on e.enumtypid = t.oid
  join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public'
  group by t.typname order by t.typname`);
const enumNames = new Set(enums.map((e) => e.name));

function tsType(udt, isArray = false) {
  let base;
  const t = isArray ? udt.replace(/^_/, "") : udt;
  if (enumNames.has(t)) base = `Database["public"]["Enums"]["${t}"]`;
  else if (["int2", "int4", "int8", "float4", "float8", "numeric", "oid"].includes(t)) base = "number";
  else if (t === "bool") base = "boolean";
  else if (["json", "jsonb"].includes(t)) base = "Json";
  else if (t === "void") base = "undefined";
  else base = "string";
  return isArray ? `${base}[]` : base;
}

const tables = await q(`
  select c.relname as name
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'r'
  order by c.relname`);

const columns = await q(`
  select table_name, column_name, is_nullable = 'YES' as nullable, column_default is not null as has_default,
         is_identity = 'YES' as identity, is_generated = 'ALWAYS' as generated, udt_name, data_type, ordinal_position
  from information_schema.columns
  where table_schema = 'public'
  order by table_name, column_name`);

const fks = await q(`
  select con.conname as name, rel.relname as table_name, frel.relname as ref_table,
         array(select a.attname::text from unnest(con.conkey) with ordinality k(attnum, ord)
               join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k.attnum order by k.ord) as columns,
         array(select a.attname::text from unnest(con.confkey) with ordinality k(attnum, ord)
               join pg_attribute a on a.attrelid = con.confrelid and a.attnum = k.attnum order by k.ord) as ref_columns,
         exists (
           select 1 from pg_index i
           where i.indrelid = con.conrelid and i.indisunique
             and (select array_agg(x order by x) from unnest(i.indkey::int2[]) x) =
                 (select array_agg(x order by x) from unnest(con.conkey) x)
         ) as one_to_one
  from pg_constraint con
  join pg_class rel on rel.oid = con.conrelid
  join pg_namespace n on n.oid = rel.relnamespace
  join pg_class frel on frel.oid = con.confrelid
  join pg_namespace fn on fn.oid = frel.relnamespace
  where con.contype = 'f' and n.nspname = 'public' and fn.nspname = 'public'
  order by con.conname`);

const funcs = await q(`
  select p.proname as name,
         p.proargnames as arg_names,
         p.proargmodes::text[] as arg_modes,
                  array(select tt.typname::text from unnest(p.proargtypes::oid[]) with ordinality u(t, ord) join pg_type tt on tt.oid = u.t order by u.ord) as in_types,
         array(select tt.typname::text from unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) with ordinality u(t, ord) join pg_type tt on tt.oid = u.t order by u.ord) as all_types,
         p.pronargs as nargs, p.pronargdefaults as ndefaults, p.proretset as returns_set,
         rt.typname as return_type, rt.typtype as return_typtype
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
  join pg_type rt on rt.oid = p.prorettype
  where n.nspname = 'public' and p.prokind = 'f' and rt.typname <> 'trigger'
  order by p.proname`);

const ind = (n) => "  ".repeat(n);
let s = `// Generated by scripts/gen-db-types.mjs from the TickLO migrations. Do not edit by hand.
export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  public: {
    Tables: {
`;

for (const { name } of tables) {
  const cols = columns.filter((c) => c.table_name === name);
  const isArr = (c) => c.data_type === "ARRAY";
  const colType = (c) => tsType(c.udt_name, isArr(c)) + (c.nullable ? " | null" : "");
  s += `${ind(3)}${name}: {\n${ind(4)}Row: {\n`;
  for (const c of cols) s += `${ind(5)}${c.column_name}: ${colType(c)};\n`;
  s += `${ind(4)}};\n${ind(4)}Insert: {\n`;
  for (const c of cols) {
    const optional = c.nullable || c.has_default || c.identity || c.generated;
    s += `${ind(5)}${c.column_name}${optional ? "?" : ""}: ${colType(c)};\n`;
  }
  s += `${ind(4)}};\n${ind(4)}Update: {\n`;
  for (const c of cols) s += `${ind(5)}${c.column_name}?: ${colType(c)};\n`;
  s += `${ind(4)}};\n${ind(4)}Relationships: [\n`;
  for (const fk of fks.filter((f) => f.table_name === name)) {
    s += `${ind(5)}{\n${ind(6)}foreignKeyName: "${fk.name}";\n${ind(6)}columns: [${fk.columns.map((x) => `"${x}"`).join(", ")}];\n`;
    s += `${ind(6)}isOneToOne: ${fk.one_to_one};\n${ind(6)}referencedRelation: "${fk.ref_table}";\n`;
    s += `${ind(6)}referencedColumns: [${fk.ref_columns.map((x) => `"${x}"`).join(", ")}];\n${ind(5)}},\n`;
  }
  s += `${ind(4)}];\n${ind(3)}};\n`;
}

s += `${ind(2)}};\n${ind(2)}Views: {\n${ind(3)}[_ in never]: never;\n${ind(2)}};\n${ind(2)}Functions: {\n`;

for (const f of funcs) {
  const names = f.arg_names ?? [];
  const modes = f.arg_modes ?? [];
  // input args are those with mode i (or no modes at all)
  const inputs = [];
  const outputs = [];
  names.forEach((n, i) => {
    const mode = modes[i] ?? "i";
    if (mode === "i" || mode === "b") inputs.push({ name: n, type: f.all_types[i] });
    if (mode === "t" || mode === "o" || mode === "b") outputs.push({ name: n, type: f.all_types[i] });
  });
  if (!modes.length) {
    inputs.length = 0;
    names.slice(0, f.nargs).forEach((n, i) => inputs.push({ name: n, type: f.in_types[i] }));
  }
  const firstDefault = f.nargs - f.ndefaults;
  let args;
  if (inputs.length === 0) args = "never";
  else {
    args = "{\n";
    inputs.forEach((a, i) => {
      const isArray = a.type.startsWith("_");
      args += `${ind(5)}${a.name}${i >= firstDefault ? "?" : ""}: ${tsType(a.type, isArray)} | null;\n`;
    });
    args += `${ind(4)}}`;
  }
  let ret;
  if (outputs.length) {
    ret = "{\n";
    for (const o of outputs) ret += `${ind(5)}${o.name}: ${tsType(o.type, o.type.startsWith("_"))};\n`;
    ret += `${ind(4)}}[]`;
  } else {
    ret = tsType(f.return_type, f.return_type.startsWith("_"));
    if (f.returns_set) ret += "[]";
  }
  s += `${ind(3)}${f.name}: {\n${ind(4)}Args: ${args};\n${ind(4)}Returns: ${ret};\n${ind(3)}};\n`;
}

s += `${ind(2)}};\n${ind(2)}Enums: {\n`;
for (const e of enums) s += `${ind(3)}${e.name}: ${e.labels.map((l) => `"${l}"`).join(" | ")};\n`;
s += `${ind(2)}};\n${ind(2)}CompositeTypes: {\n${ind(3)}[_ in never]: never;\n${ind(2)}};\n${ind(1)}};\n};\n\n`;

s += `type PublicSchema = Database["public"];
export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"];
export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"];
export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"];
export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T];
`;

writeFileSync(out, s);
await client.end();
console.log(`Wrote ${path.relative(process.cwd(), out)} (${tables.length} tables, ${funcs.length} functions, ${enums.length} enums)`);
